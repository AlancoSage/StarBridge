"""Embed the unmodified official Source Han Sans CN variable WOFF2 font.

The official region-specific Simplified Chinese font from Adobe Source Han Sans
2.005R provides weights 250 through 900. Only Base64 packaging is applied; the
font bytes, glyphs, names, copyright, and license metadata remain unchanged.

Download SOURCE_URL, then run:
    python scripts/build_panel_font.py path/to/SourceHanSansCN-VF.ttf.woff2

The generated Python module is compatible with existing update runtimes that
allow Python source files but do not accept standalone WOFF2 assets.
"""
import argparse
import base64
import hashlib
from pathlib import Path


UPSTREAM_COMMIT = "6c709ca72d3d7c46ab42ebecc1a26e7d69595a37"
SOURCE_PATH = "Variable/WOFF2/TTF/Subset/SourceHanSansCN-VF.ttf.woff2"
SOURCE_URL = (
    "https://raw.githubusercontent.com/adobe-fonts/source-han-sans/"
    f"{UPSTREAM_COMMIT}/{SOURCE_PATH}"
)
SHA256 = "f971e3bff46f76b49e1d5510556c2297c618ec4b491a295a4e741cdd38257799"
FONT_URL = f"/fonts/source-han-sans-sc-{SHA256[:16]}.woff2"
FONT_SIZE = 7_711_988


def build(source: Path, output: Path) -> None:
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Font differs from the pinned official upstream file")
    if len(data) != FONT_SIZE or data[:4] != b"wOF2":
        raise ValueError("Pinned font is not the expected WOFF2 file")
    encoded = base64.b64encode(data).decode("ascii")
    lines = [
        '"""Unmodified Source Han Sans CN variable WOFF2 for the console.',
        "Copyright 2014-2025 Adobe, with Reserved Font Name 'Source'.",
        "Licensed under SIL OFL 1.1; docs/source-han-sans-license.md has the full text.",
        "The official font's original names, copyright, and license metadata are retained.",
        "Generated by scripts/build_panel_font.py using reversible Base64 packaging.",
        f"Upstream: adobe-fonts/source-han-sans {UPSTREAM_COMMIT} (2.005R).",
        '"""',
        "from base64 import b64decode",
        "from functools import lru_cache",
        "",
        f"SHA256 = {SHA256!r}",
        f"FONT_URL = {FONT_URL!r}",
        f"FONT_SIZE = {FONT_SIZE!r}",
        f"UPSTREAM_URL = {SOURCE_URL!r}",
        "",
        "",
        "@lru_cache(maxsize=1)",
        "def font_data():",
        '    """Return the exact upstream WOFF2 bytes, decoded once per process."""',
        "    return b64decode(",
        *("        b" + repr(encoded[offset:offset + 100])
          for offset in range(0, len(encoded), 100)),
        "    )",
        "",
    ]
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Embedded pinned font: {len(data)} bytes; module {output.stat().st_size} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "starbridge/panel_font.py",
    )
    args = parser.parse_args()
    build(args.source, args.output)
