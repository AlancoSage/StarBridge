"""Embed the unmodified Noto Sans SC font in an old-updater-compatible module.

Input: Sans/SubsetOTF/SC/NotoSansSC-Regular.otf from notofonts/noto-cjk,
commit f8d157532fbfaeda587e826d4cd5b21a49186f7c (SIL OFL 1.1).
"""
import argparse
import base64
import hashlib
import lzma
from pathlib import Path
import struct
import textwrap

SHA256 = "faa6c9df652116dde789d351359f3d7e5d2285a2b2a1f04a2d7244df706d5ea9"


def build(source, output):
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Font differs from the pinned upstream file")
    tables = {data[pos:pos+4]: struct.unpack_from('>II', data, pos+8) for pos in range(12, 12+16*struct.unpack_from('>H', data, 4)[0], 16)}
    start = tables[b'cmap'][0]
    ranges = None
    for pos in range(start+4, start+4+8*struct.unpack_from('>H', data, start+2)[0], 8):
        platform, encoding, offset = struct.unpack_from('>HHI', data, pos)
        table = start+offset
        if (platform == 0 or (platform, encoding) == (3, 10)) and struct.unpack_from('>H', data, table)[0] == 12:
            ranges = [struct.unpack_from('>III', data, row) for row in range(table+16, table+16+12*struct.unpack_from('>I', data, table+12)[0], 12)]
            break
    if ranges is None:
        raise ValueError("Pinned font has no Unicode cmap12")
    supported = [(lo+(glyph == 0), hi) for lo, hi, glyph in ranges if lo+(glyph == 0) <= hi]
    encoded = base64.b85encode(lzma.compress(data, preset=9)).decode('ascii')
    lines = [
        '"""Unmodified Noto Sans SC, embedded for existing update runtimes.',
        'Font copyright and SIL OFL 1.1 are retained in its binary name table;',
        'full license: docs/noto-font-license.md. Generated by scripts/build_reply_font.py.',
        'Upstream: notofonts/noto-cjk f8d157532fbfaeda587e826d4cd5b21a49186f7c.',
        '"""', 'from base64 import b85decode', 'from functools import lru_cache', 'import lzma', '',
        f'SHA256 = {SHA256!r}', f'SUPPORTED_RANGES = {supported!r}', '', '@lru_cache(maxsize=1)',
        'def font_data():', '    return lzma.decompress(b85decode(',
        *('        '+repr(line) for line in textwrap.wrap(encoded, 100, break_on_hyphens=False)),
        '    ))', '',
    ]
    output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Embedded pinned font: {len(data)} bytes; module {output.stat().st_size} bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent.parent/'starbridge/reply_font.py')
    args = parser.parse_args()
    build(args.source, args.output)
